/* --- STATE & INITIALIZATION --- */
let currentLang = 'sr';
let activeCategory = 'all';

document.addEventListener('DOMContentLoaded', () => {
  // Mobile Menu Toggle
  const burgerBtn = document.getElementById('burgerBtn');
  const mobileMenu = document.getElementById('mobileMenu');
  
  burgerBtn.addEventListener('click', () => {
    mobileMenu.classList.toggle('active');
  });

  document.querySelectorAll('.mobile-link').forEach(link => {
    link.addEventListener('click', () => {
      mobileMenu.classList.remove('active');
    });
  });

  // Language Switching Handlers
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const lang = e.target.getAttribute('data-lang');
      setLanguage(lang);
    });
  });

  // Render initial language & dynamic views
  setLanguage('sr');

  // Set Current Year in Footer
  document.getElementById('year').textContent = new Date().getFullYear();
});

/* --- LANGUAGE SWITCHER FUNCTION --- */
function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;

  // Update active state on language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Update plain text attributes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Re-render Meni & Reviews in the new language
  renderMenuTabs();
  renderMenuContent();
  renderReviews();
}

/* --- RENDER MENU TABS & ITEMS --- */
function renderMenuTabs() {
  const tabsContainer = document.getElementById('menuTabs');
  tabsContainer.innerHTML = '';

  // "All" tab
  const allBtn = document.createElement('button');
  allBtn.className = `tab-btn ${activeCategory === 'all' ? 'active' : ''}`;
  allBtn.textContent = translations[currentLang].tab_all || "Sve";
  allBtn.addEventListener('click', () => {
    activeCategory = 'all';
    renderMenuTabs();
    renderMenuContent();
  });
  tabsContainer.appendChild(allBtn);

  // Category tabs
  Object.keys(menuData).forEach(catKey => {
    const btn = document.createElement('button');
    btn.className = `tab-btn ${activeCategory === catKey ? 'active' : ''}`;
    btn.textContent = menuData[catKey].category[currentLang];
    btn.addEventListener('click', () => {
      activeCategory = catKey;
      renderMenuTabs();
      renderMenuContent();
    });
    tabsContainer.appendChild(btn);
  });
}

function renderMenuContent() {
  const container = document.getElementById('menuContent');
  container.innerHTML = '';

  const categoriesToRender = activeCategory === 'all' 
    ? Object.keys(menuData) 
    : [activeCategory];

  categoriesToRender.forEach(catKey => {
    const catData = menuData[catKey];
    
    const block = document.createElement('div');
    block.className = 'menu-category-block';

    const catTitle = document.createElement('h3');
    catTitle.className = 'category-title';
    catTitle.textContent = catData.category[currentLang];
    block.appendChild(catTitle);

    const grid = document.createElement('div');
    grid.className = 'menu-items-grid';

    catData.items.forEach(item => {
      const card = document.createElement('div');
      card.className = 'menu-item-card';

      card.innerHTML = `
        <div>
          <div class="menu-item-header">
            <h4 class="menu-item-name">${item.name[currentLang]}</h4>
            <span class="menu-item-price">${item.price}</span>
          </div>
          <p class="menu-item-desc">${item.desc[currentLang]}</p>
        </div>
        ${item.weight && item.weight !== '-' ? `<span class="menu-item-weight">${item.weight}</span>` : ''}
      `;
      grid.appendChild(card);
    });

    block.appendChild(grid);
    container.appendChild(block);
  });
}

